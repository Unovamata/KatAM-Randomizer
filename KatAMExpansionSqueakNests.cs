        /* SqueakNestArt(); A nest as a Squeak Squad character (SqueakFrames() cuts it into KatAM's frames as the DS's): its tiles in
         * 32 by 32 pieces, its feet (the bottom's middle) on the spot, one cell, one animation; "stump" or "rock"; */
        static SqueakCharacter SqueakNestArt(string name) {
            (ushort[] colors, string[] rows) = name == "rock" ? (RockNestColors, RockNestArt) : (StumpNestColors, StumpNestArt);
            int width = rows[0].Length, height = rows.Length, across = (width + 31) / 32, down = (height + 31) / 32;
            byte[] tiles = new byte[across * down * 16 * 32];
            List<SqueakPiece> pieces = new List<SqueakPiece>();
            for (int py = 0; py < down; py++)
                for (int px = 0; px < across; px++) {
                    int piece = py * across + px;
                    for (int y = 0; y < 32; y++)
                        for (int x = 0; x < 32; x++) {
                            int ax = px * 32 + x, ay = py * 32 + y;
                            if (ax >= width || ay >= height || rows[ay][ax] == '.') continue;
                            int value = Convert.ToInt32(rows[ay][ax].ToString(), 16) + 1, at = (piece * 16 + y / 8 * 4 + x / 8) * 32 + y % 8 * 4 + x % 8 / 2;
                            tiles[at] |= (byte)(value << (x % 2 * 4));
                        }
                    pieces.Add(new SqueakPiece(py * 32 - height & 0xFF, (px * 32 - width / 2 & 0x1FF) | 2 << 14, piece * 4));
                }
            return new SqueakCharacter {
                Tiles = tiles, Palettes = new List<ushort[]> { colors },
                Cells = new List<SqueakCell> { new SqueakCell(0, pieces) },
                Anims = new List<SqueakAnim> { new SqueakAnim(true, new List<SqueakStep> { new SqueakStep(0, 1, 0, 0) }) },
                Compositions = new List<List<SqueakPart>>(), Composites = new List<SqueakComposite>(),
            };
        }
