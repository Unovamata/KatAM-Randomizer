// EndShake(); How far down the screen's shaken at t;
static s32 EndShake(u16 t) {
    u8 i;

    if (t < END_SHAKE) return 0;
    t -= END_SHAKE;
    for (i = 0; i < ARRAY_COUNT(sEndShake); i++) {
        if (t < sEndShake[i][1]) return sEndShake[i][0] * sShakeSteps[t & 3];
        t -= sEndShake[i][1];
    }
    return 0;
}

// EndHidden(); Whether the warp star and its Kirbys are hidden at t (in the moon, off the screen);
static bool32 EndHidden(u16 t) {
    return t < END_STAR || (t >= END_UP && t < END_BACK) || (t >= END_RIGHT && t < END_FULL);
}

static void EndingMain(void);

// EndingOf(); The ending in a room (its task), or NULL;
static struct Ending *EndingOf(u16 room) {
    struct Task *t = &gTasks[0];
    u8 n;

    for (n = 0; n < MAX_TASK_NUM && t->next; n++) {
        struct Ending *end;

        t = (struct Task *)(IWRAM_START + t->next);
        if (t->main != EndingMain) continue;
        end = TaskGetStructPtr(t);
        if (end->e.roomId == room && !(end->e.flags & 0x1000)) return end;
    }
    return NULL;
}

// EndRider(); Whether a Kirby is held on the ending's ride in a room (its step NIDL_RIDE_FINALE: warpstar.c);
static bool32 EndRider(struct Kirby *kirby, u16 room) {
    const struct Unk_08353510 *step = kirby->unk114;

    return kirby->base.roomId == room && NidlOnEnding(kirby) && step->unk8 == NIDL_RIDE_FINALE && !(step->unk9 & 0x40);
}

// EndPalette(); A palette's slot, loaded under `key` as frame `frame` of the anim in its low 12 bits has it, or 0 (not yet: the
// local player isn't in the room);
static u8 EndPalette(u16 room, u16 key, u8 frame) {
    u8 palId = sub_0803DF24(key);

    if (palId == 0xFF) {
        if (gKirbys[gLocalPlayerId].base.roomId != room) return 0;
        sub_0803DFAC(key, frame);
        palId = sub_0803DF24(key);
    }
    return palId == 0xFF ? 0 : palId;
}

static void EndSpriteMain(void) {
    struct EffectObject *e = TaskGetStructPtr(gCurTask);

    if (e->flags & 0x1000) TaskDestroy(gCurTask);
}

// EndSprite(); A sprite of the ending's (`tiles` tiles of VRAM, frame `frame` first, in front of others by `order`): a task of its
// own (KatAM frees its VRAM with it), drawn by the ending (EndDraw()), gone with it (its flag 0x1000);
static struct EffectObject *EndSprite(u16 room, u16 tiles, u8 frame, u8 order) {
    struct Task *t = TaskCreate(EndSpriteMain, sizeof(struct EffectObject), 0x3500, TASK_USE_EWRAM, ObjectBaseDestroy);
    struct EffectObject *e = TaskGetStructPtr(t);

    ClearEffectObject(e);
    e->header.kind = 3;
    e->roomId = room;
    e->parent = NULL;
    e->flags |= 0x400;
    EffectObjectInitSprite(e, &e->sprite, tiles, gNidlData.bosses[NIDL_NIGHTMARE].animId, frame, order);
    return e;
}

// EndRelease(); A sprite of the ending's let go (its task ends);
static void EndRelease(struct EffectObject **e) {
    if (*e == NULL) return;
    (*e)->flags |= 0x1000;
    *e = NULL;
}

// EndDraw(); A sprite of the ending's at (x, y) on the screen (pixels: NiDL's cutscene objects are the screen's), frame `frame`,
// palette `palId`, mirrored or not (KatAM draws effects mirrored unless they face right: NiDL draws its effects as they are, but
// what faces as its star);
static void EndDraw(struct EffectObject *e, s32 x, s32 y, u8 frame, u8 palId, bool8 mirrored) {
    struct LevelInfo *view = &gCurLevelInfo[gLocalPlayerId];

    e->x = view->viewportPosition.x + (x << 8);
    e->y = view->viewportPosition.y + (y << 8);
    e->sprite.variant = frame;
    e->sprite.palId = palId;
    e->flags = (e->flags & ~0x401) | 4 | (mirrored ? 0 : 1);
    EffectObjectPostUpdate(e);
}

// EndShow(); A sprite of the ending's (made as it's needed) drawn: EndDraw();
static void EndShow(struct Ending *end, struct EffectObject **e, u16 tiles, u8 order, s32 x, s32 y, u8 frame, u8 palId, bool8 mirrored) {
    if (*e == NULL) *e = EndSprite(end->e.roomId, tiles, frame, order);
    EndDraw(*e, x, y, frame, palId, mirrored);
}

// EndGone(); Its sprites let go;
static void EndGone(struct Ending *end) {
    u8 i;

    for (i = 0; i < 8; i++) EndRelease(&end->ring[i]);
    EndRelease(&end->centre);
    EndRelease(&end->twinkle);
    EndRelease(&end->trail);
    EndRelease(&end->puff);
    EndRelease(&end->dedede);
    for (i = 0; i < SPARKS; i++) EndRelease(&end->sparks[i].e);
}

// EndCrescent(); The moon a crescent: sCrescent in the room's tilemap (every player's in the room), redrawn;
static void EndCrescent(u16 room) {
    u8 i, k;

    for (i = 0; i < gNumKirbys; i++) {
        struct LevelInfo *l = &gCurLevelInfo[i];
        u16 *map = (u16 *)l->unk180[0].tilemap, width = l->roomWidth >> 3;

        if (l->currentRoom != room) continue;
        for (k = 0; k < ARRAY_COUNT(sCrescent); k++) map[sCrescent[k].y * width + sCrescent[k].x] = sCrescent[k].entry - MOON_SHIFT;
        l->unkC0[1].prevScrollX = 0x7FFF;
        l->unkC0[1].prevScrollY = 0x7FFF;
    }
}

// EndBurst(); The moon's burst at t (sEndBurst);
static void EndBurst(struct Ending *end, u16 t) {
    const u8 *b;
    u8 i;

    if (t < END_BURST) return;
    if (t - END_BURST >= ARRAY_COUNT(sEndBurst) / 4) {
        for (i = 0; i < 8; i++) EndRelease(&end->ring[i]);
        EndRelease(&end->centre);
        return;
    }
    b = &sEndBurst[(t - END_BURST) * 4];
    for (i = 0; i < 8; i++) {
        u8 apart = i < 4 ? b[1] : b[2];
        s32 x = END_BURST_X + (sRing[i][0] > 0 ? apart >> 1 : sRing[i][0] < 0 ? -((apart + 1) >> 1) : 0);
        s32 y = END_BURST_Y + (sRing[i][1] > 0 ? apart >> 1 : sRing[i][1] < 0 ? -((apart + 1) >> 1) : 0);

        if (b[0] == NONE) {
            if (end->ring[i] != NULL) end->ring[i]->flags |= 0x400;
            continue;
        }
        EndShow(end, &end->ring[i], RING_TILES, ORDER_FX, x, y, FRAME_BURST + b[0], end->fxPal, FALSE);
    }
    if (b[3] == NONE) {
        if (end->centre != NULL) end->centre->flags |= 0x400;
    } else {
        EndShow(end, &end->centre, BURST_TILES, ORDER_FX, END_BURST_X, END_BURST_Y, FRAME_BURST + b[3], end->fxPal, FALSE);
    }
}

// EndRiders(); The Kirbys on the ride moved with the star, each given his warp star once (hidden till it shows), facing left;
// once it's still, on to the fade (their flight's next step);
static void EndRiders(struct Ending *end, u16 t) {
    struct LevelInfo *view = &gCurLevelInfo[gLocalPlayerId];
    s32 x = end->starX, y = end->starY;
    u8 i;

    if (EndHidden(t)) {
        x = x < END_LEFT ? END_LEFT : x > END_RIGHT_EDGE ? END_RIGHT_EDGE : x;
        y = y < END_UPPER ? END_UPPER : y > END_LOWER ? END_LOWER : y;
    }
    for (i = 0; i < gNumKirbys; i++) {
        struct Kirby *kirby = &gKirbys[i];

        if (!EndRider(kirby, end->e.roomId)) continue;
        if (!((end->riders >> i) & 1)) {
            end->riders |= 1 << i;
            sub_0808EDB8(kirby);
        }
        kirby->base.x = view->viewportPosition.x + (x << 8);
        kirby->base.y = view->viewportPosition.y + (y << 8);
        kirby->base.flags |= 1;
        if (t >= END_SETTLE) {
            kirby->unk114++;
            kirby->base.counter = ((const struct Unk_08353510 *)kirby->unk114)->unk4;
        }
    }
}

// EndTrail(); The warp star's trail at t (once it's at its size: see above), and the twinkle where it comes out;
static void EndTrail(struct Ending *end, u16 t) {
    u16 k;

    if (t == END_TWINKLE) {
        end->twinkleX = END_TWINKLE_X;
        end->twinkleY = END_TWINKLE_Y;
        end->twinkleAge = 0;
    }
    if (t >= END_FULL) {
        k = (t - END_FULL) % TWINKLE_EVERY;
        if (k == 0 || k == 6 || k == 27) {
            end->twinkleX = end->starX + 8 + Rand16() % 32;
            end->twinkleY = end->starY - 16 + Rand16() % 32;
            end->twinkleAge = 0;
        }
        EndShow(end, &end->trail, SPARK_TILES, ORDER_FX, end->starX + TRAIL_X + (t & 1), end->starY,
                FRAME_SPARKS + ((t - END_FULL + 8) >> 1) % 4, end->fxPal, TRUE);
        if (t >= PUFF_FIRST && (t - PUFF_FIRST) % PUFF_EVERY == 0) {
            end->puffX = (end->starX + 9 + Rand16() % 14) << 8;
            end->puffY = end->starY - 5 + Rand16() % 9;
            end->puffAge = 0;
        } else if (t > PUFF_FIRST) {
            end->puffX += (end->starDx << 8) + 0x100 + end->puffAge * 0x40;
            end->puffY += end->starDy;
            end->puffAge++;
        }
        if (t >= PUFF_FIRST && end->puffAge < PUFF_FRAMES)
            EndShow(end, &end->puff, SPARK_TILES, ORDER_FX, end->puffX >> 8, end->puffY, FRAME_SPARKS + 4 + end->puffAge / 2, end->fxPal, TRUE);
    }
    if ((t == END_TWINKLE || t > END_TWINKLE) && end->twinkleAge < TWINKLE_FRAMES) {
        EndShow(end, &end->twinkle, SPARK_TILES, ORDER_FX, end->twinkleX, end->twinkleY, FRAME_SPARKS + 9 + end->twinkleAge, end->fxPal, FALSE);
        end->twinkleAge++;
    } else if (end->twinkle != NULL) {
        end->twinkle->flags |= 0x400;
    }
}

// EndSparks(); The small stars the warp star throws out at t (see above): each a sprite of its own while it's on the screen;
static void EndSparks(struct Ending *end, u16 t) {
    static const u8 sKinds[4][2] = { { 0, 23 }, { 16, 19 }, { 32, 15 }, { 40, 15 } };
    u8 i, k;

    if (t >= SPARKS_FIRST) {
        for (k = 0; k < ARRAY_COUNT(sKinds); k++) {
            if ((t - SPARKS_FIRST) % SPARKS_EVERY != sKinds[k][0]) continue;
            for (i = 0; i < SPARKS && end->sparks[i].frame; i++)
                ;
            if (i >= SPARKS) break;
            end->sparks[i].x = (end->starX + 1) << 8;
            end->sparks[i].y = end->starY - 10 + Rand16() % 17;
            end->sparks[i].speed = SPARK_SPEED;
            end->sparks[i].frame = sKinds[k][1];
            end->sparks[i].age = 0;
        }
    }
    for (i = 0; i < SPARKS; i++) {
        struct EndSpark *s = &end->sparks[i];

        if (!s->frame) continue;
        s->x += s->speed;
        s->speed += SPARK_SPEEDUP;
        if (s->x >= SPARK_OUT) {
            s->frame = 0;
            EndRelease(&s->e);
            continue;
        }
        EndShow(end, &s->e, SPARK_TILES, ORDER_FX, s->x >> 8, s->y, FRAME_SPARKS + s->frame + (s->age / 3) % 4, end->fxPal, FALSE);
        s->age++;
    }
}

// EndDedede(); King Dedede flying by at NiDL's frame t, from the frame after `from` (sEndDedede);
static void EndDedede(struct Ending *end, u16 from, u16 t) {
    u16 k;
    u8 code, frame;

    if (t < END_DEDEDE) return;
    if (t - END_DEDEDE > ARRAY_COUNT(sEndDedede)) {
        EndRelease(&end->dedede);
        return;
    }
    for (k = from < END_DEDEDE ? END_DEDEDE : from; k <= t; k++) {
        if (k == END_DEDEDE) {
            end->dededeX = END_DEDEDE_X;
            end->dededeY = END_DEDEDE_Y;
        } else {
            code = sEndDedede[k - END_DEDEDE - 1];
            end->dededeX += (s8)(code << 4) >> 4;
            end->dededeY += (s8)code >> 4;
        }
    }
    frame = t < END_DEDEDE_FAR ? 0 : 1 + (t - END_DEDEDE_FAR) / END_DEDEDE_TURN;
    if (frame > 3) frame = 3;
    EndShow(end, &end->dedede, DEDEDE_TILES, ORDER_DEDEDE, end->dededeX, end->dededeY, FRAME_DEDEDE + frame,
            frame ? end->farPal : end->dededePal, FALSE);
}

static void EndingMain(void) {
    struct Ending *end = TaskGetStructPtr(gCurTask);
    struct EffectObject *e = &end->e;
    u16 animId = gNidlData.bosses[NIDL_NIGHTMARE].animId, t, u, from, k;
    s32 top;
    u8 i, code;

    if (e->flags & 0x1000) {
        EndGone(end);
        TaskDestroy(gCurTask);
        return;
    }
    // (gone with the room: every Kirby left it);
    for (i = 0; i < gNumKirbys; i++)
        if (gKirbys[i].base.roomId == e->roomId) break;
    if (i >= gNumKirbys) {
        EndGone(end);
        e->flags |= 0x1000;
        return;
    }
    e->flags |= 4 | 0x400;
    t = end->t++;
    // (NiDL's frames since the last: one a frame, RIDE_SPEED on the ride down);
    u = t <= END_SCROLL ? t : END_SCROLL + (t - END_SCROLL) * RIDE_SPEED;
    from = t ? end->u + 1 : 0;
    end->u = u;
    // (the screen: at the moon, shaking, then scrolling down);
    top = END_TOP + (u > END_SCROLL ? (u - END_SCROLL) * 3 >> 4 : 0) + EndShake(u);
    NidlFinaleHoldCamera(e->roomId, END_CAM_X, top << 8);
    // (the palettes, once the local player's in the room: the shared effects' palette 15, as the bursts' in Nightmare's defeat);
    if (!end->fxPal) end->fxPal = EndPalette(e->roomId, gNidlData.enemies[NIDL_SPIT_STAR].animId, 0);
    if (!end->dededePal) end->dededePal = EndPalette(e->roomId, animId | KEY_DEDEDE, FRAME_DEDEDE);
    if (!end->farPal) end->farPal = EndPalette(e->roomId, animId | KEY_DEDEDE_FAR, FRAME_DEDEDE + 1);
    if (t == END_CRESCENT) EndCrescent(e->roomId);
    // (the warp star: out of the moon, then its moves, each of NiDL's frames since the last);
    end->starDx = end->starDy = 0;
    for (k = from; k <= u; k++) {
        if (k <= END_STAR) {
            end->starX = END_STAR_X;
            end->starY = END_STAR_Y;
        } else if (k - END_STAR - 1 < ARRAY_COUNT(sEndStar)) {
            code = sEndStar[k - END_STAR - 1];
            end->starDx += (s8)(code << 4) >> 4;
            end->starDy += (s8)code >> 4;
            end->starX += (s8)(code << 4) >> 4;
            end->starY += (s8)code >> 4;
        }
    }
    EndRiders(end, u);
    EndBurst(end, u);
    // (its trail and small stars on the game's frames: their own pace, sped up or not);
    EndTrail(end, t);
    EndSparks(end, t);
    EndDedede(end, from, u);
}

/* NidlEndingRider(); A Kirby held on the ending's ride (finale.c's NidlFinaleHold(), every frame): its task made, as the first one
 * comes into the room (it moves them all); */
void NidlEndingRider(struct Kirby *kirby) {
    struct Task *task;
    struct Ending *end;

    if (EndingOf(kirby->base.roomId) != NULL) return;
    task = TaskCreate(EndingMain, sizeof(struct Ending), 0x3500, TASK_USE_EWRAM, ObjectBaseDestroy);
    end = TaskGetStructPtr(task);
    CpuFill16(0, end, sizeof(struct Ending));
    ClearEffectObject(&end->e);
    end->e.header.kind = 3;
    end->e.roomId = kirby->base.roomId;
    end->e.parent = NULL;
    end->e.flags |= 0x400;
    end->starX = END_STAR_X;
    end->starY = END_STAR_Y;
}

/* NidlEndingRideSize(); The size the ending's warp stars and their Kirbys are drawn at (warpstar.c: their steps ask it): its matrix's
 * pa (256 / the size, 8.8), 0 their own, NIDL_RIDE_HIDDEN not shown (in the moon, off the screen, or the ending not there yet); as
 * the Kirbys were last moved (EndRiders(), end->u: the stars are drawn before it moves them, kept on the screen while hidden, which
 * showed a star there for a frame as they came back); */
u32 NidlEndingRideSize(u16 room) {
    struct Ending *end = EndingOf(room);
    u16 t;

    if (end == NULL || !end->t || EndHidden(t = end->u)) return NIDL_RIDE_HIDDEN;
    if (t < END_FULL) return 0x10000 / (END_SIZE_FIRST + END_SIZE_MORE * ((t - END_STAR) / END_SIZE_EVERY));
    return 0;
}

// NidlEndingOn(); Whether the ending's in a room (its task, or a Kirby on its flight there: nidl_boss.c keeps the Power Orb away);
bool32 NidlEndingOn(u16 room) {
    u8 i;

    if (EndingOf(room) != NULL) return TRUE;
    for (i = 0; i < gNumKirbys; i++)
        if (gKirbys[i].base.roomId == room && NidlOnEnding(&gKirbys[i])) return TRUE;
    return FALSE;
}
