#!/bin/bash
# Builds the NiDL enemies (nidl.c, nidl_data.c, enemies/*.c) into the code KatAMExpansion.cs embeds, linked at 0x08F60000,
# and writes ../KatAMExpansionCode.cs with the code and the symbols KatAMExpansion.cs needs;
# Needs the KatAM decompilation (https://github.com/jiangzhengwenjz/katam) built for the USA version (katam.elf), with agbcc
# installed in it, and arm-none-eabi binutils. Usage: ./build.sh /path/to/katam;
set -e
D=${1:?path to the katam decompilation}
BASE=0x08F60000
OUT=$(mktemp -d)
trap 'rm -rf "$OUT"' EXIT

objects=()
for c in nidl.c nidl_data.c enemies/*.c; do
    o="$OUT/$(basename "${c%.c}").o"
    cpp -I "$D/tools/agbcc/include" -I "$D/tools/agbcc" -nostdinc -iquote "$D/include" -iquote . -DREVISION=0 -DENGLISH \
        -Wno-trigraphs -DMODERN=0 "$c" | "$D/tools/agbcc/bin/agbcc" -mthumb-interwork -Wimplicit -Wparentheses -O2 -fhex-asm -o "$OUT/a.s" -
    arm-none-eabi-as -mcpu=arm7tdmi -o "$o" "$OUT/a.s"
    objects+=("$o")
done

arm-none-eabi-ld -Ttext=$BASE --just-symbols="$D/katam.elf" -e CreateNidlEnemy -o "$OUT/nidl.elf" "${objects[@]}"
arm-none-eabi-objcopy -O binary "$OUT/nidl.elf" "$OUT/nidl.bin"

# KatAMExpansionCode.cs: the code and the offsets (from 0x08F60000) of the symbols KatAMExpansion.cs uses;
python3 - "$OUT/nidl.bin" "$OUT/nidl.elf" > ../KatAMExpansionCode.cs <<'PY'
import subprocess, sys
code = open(sys.argv[1], 'rb').read()
syms = {}
for line in subprocess.run(['arm-none-eabi-nm', sys.argv[2]], capture_output=True, text=True, check=True).stdout.splitlines():
    parts = line.split()
    if len(parts) == 3: syms[parts[2]] = int(parts[0], 16) - 0x08F60000
names = ['CreateNidlEnemy', 'NidlStart', 'NidlCopyName', 'gNidlData']
print('namespace KatAMRandomizer {')
print('    // Generated by "ROM Expansion/build.sh" from the C sources there: the NiDL enemies\' code, linked at 0x08F60000;')
print('    internal static class KatAMExpansionCode {')
for n in names:
    print(f'        public const int {n[0].upper() + n[1:]} = 0x{syms[n]:X};')
print('        public static readonly byte[] Code = {')
for i in range(0, len(code), 24):
    print('            ' + ' '.join(f'0x{b:02X},' for b in code[i:i + 24]))
print('        };')
print('    }')
print('}')
PY
echo "$(stat -c %s "$OUT/nidl.bin") bytes of code"
